"""Benchmark scenarios for the sales agent. Fictional data: the Demo Realty catalog from app.seed.

Each scenario is one customer turn, optionally after a short history or a
remembered summary. Expectations are split in two:

- deterministic checks (`handoff`, `include`, `exclude`, `language`, voice
  format) — cheap, objective, and the primary score;
- `ideal` — what a good manager would do and where the trap is, for the judge.

`include` is a list of groups; every group must match, any item inside a group
is enough. Matching runs on a normalized answer: lowercase, ё→е, digit groups
joined ("85 000" → "85000") and number words turned into digits.
`exclude` items are regular expressions on the same normalized text.
"""

