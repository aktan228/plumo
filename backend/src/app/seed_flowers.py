async def seed_flowers(session) -> Business:
    """Insert or refresh the flower shop and its catalog."""

    businesses = BusinessRepository(session)
    knowledge = KnowledgeRepository(session)
    now = utcnow()

    # By id first: a renamed shop is the same row, not a second business.
    business = await businesses.get(FLOWERS_BUSINESS_ID) or await businesses.get_by_name(FLOWERS_NAME)
    if business is None:
        business = Business(
            id=FLOWERS_BUSINESS_ID,
            name=FLOWERS_NAME,
            description=_DESCRIPTION,
            working_hours=_HOURS,
            contacts=dict(_CONTACTS),
            rules=_RULES,
            profile=dict(_PROFILE),
            created_at=now,
            updated_at=now,
        )
        await businesses.add(business)
    else:
        row = await session.get(BusinessRow, business.id)
        if row is not None:
            row.name = FLOWERS_NAME
            row.description = _DESCRIPTION
            row.working_hours = _HOURS
            row.contacts = {**(row.contacts or {}), **_CONTACTS}
            row.rules = _RULES
            row.profile = dict(_PROFILE)
            row.updated_at = now
            await session.flush()
            business = await businesses.get(business.id) or business

    for number, (category, title, content) in enumerate((*CATALOG, *FAQ), start=1):
        existing = await knowledge.get_by_title(business.id, title)
        if existing is not None:
            # The catalog in this file is the source: edits reach the database on reseed.
            row = await session.get(KnowledgeItemRow, existing.id)
            if row is not None and (row.category, row.content) != (category, content):
                row.category, row.content, row.updated_at = category, content, now
            continue
        await knowledge.add(
            KnowledgeItem(
                id=_id(number),
                business_id=business.id,
                category=category,
                title=title,
                content=content,
                metadata={},
                active=True,
                created_at=now,
                updated_at=now,
            )
        )
    return business
