"""Customer personas for the dialog eval. Budgets match the demo catalog in app.seed.

The card is all the simulated customer knows: no agent prompt, no business data.
Phone numbers are fictional (+996 555 0xx xxx).
"""

from __future__ import annotations

from dataclasses import dataclass

# Handoff reasons a customer's own words justify at any point.
CUSTOMER_REASONS = frozenset({"user_requested_human", "ready_for_meeting", "hot_lead", "model_unavailable"})


@dataclass(frozen=True, slots=True)
class Persona:
    id: str
    title: str
    # What the customer wants to do with the flat.
    wants: str  # "buy" | "rent"
    # Languages the agent may answer in; "mixed" is what detect_language says for ru+ky.
    languages: tuple[str, ...]
    opening: str
    card: str
    phone: str
    # Reasons besides CUSTOMER_REASONS that are fine for this persona.
    extra_reasons: frozenset[str] = frozenset()
    # A handoff with one of these reasons must happen in the dialog.
    required_reasons: frozenset[str] = frozenset()
    # Lines for --mock: the whole pipeline without a simulator model.
    mock_lines: tuple[str, ...] = ()

    @property
    def allowed_reasons(self) -> frozenset[str]:
        return CUSTOMER_REASONS | self.extra_reasons


